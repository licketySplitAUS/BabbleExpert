'use strict';
const { app, BrowserWindow, ipcMain } = require('electron');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), assert = require('node:assert/strict');
const { makeBabbleGlowScript } = require('../../src/babble-glow');
app.disableHardwareAcceleration();
app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'be-tile-undo-')));
ipcMain.handle('create-clues:enabled', () => false);
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, webPreferences: { preload: path.resolve(__dirname, '../../src/preload-puzzle.js'), sandbox: true, contextIsolation: true } });
  const run = code => win.webContents.executeJavaScript(code);
  const previews = [];
  ipcMain.on('clues:entry', (_event, phase, word) => { if (phase === 'preview') previews.push(word); });
  await win.loadFile(path.join(__dirname, 'fixtures/clues.html'));
  async function legacyClick(index) { await run("document.querySelectorAll('#clue-grid img')[" + index + "].click()"); await sleep(20); }
  const clueWord = () => run("document.forms.myForm.addWord.value");
  await legacyClick(0); await legacyClick(1);
  assert.equal(await clueWord(), 'br');
  await legacyClick(1); assert.equal(await clueWord(), 'b');
  await legacyClick(0); assert.equal(await clueWord(), '');
  assert.ok(previews.includes('b') && previews.includes(''), 'Undo previews the shorter word');
  await run("document.querySelectorAll('#clue-grid img')[0].setAttribute('onclick', \"addLetter('Qu')\")");
  await legacyClick(0); assert.equal(await clueWord(), 'qu');
  await legacyClick(0); assert.equal(await clueWord(), '', 'Qu removes the entire tile');
  await legacyClick(5); await legacyClick(9);
  assert.equal(await clueWord(), 'aa', 'Equal letters on different tiles still append');
  await legacyClick(9); assert.equal(await clueWord(), 'a');
  await win.loadFile(path.join(__dirname, 'fixtures/babble.html'));
  await run(makeBabbleGlowScript(['']));
  const babbleWord = () => run("document.forms.add_word.elements.word.value");
  const click = index => run("document.querySelectorAll('#left_column img')[" + index + "].click()");
  await click(0); await click(1); await click(1);
  assert.equal(await babbleWord(), 'b');
  assert.equal(await run("document.querySelector('.be-live').dataset.tiles"), '1');
  await click(0); assert.equal(await babbleWord(), '');
  await run("document.querySelectorAll('#left_column img')[0].src='/images/q.gif'; window.__babbleExpertGlow.refresh()");
  await click(0); assert.equal(await babbleWord(), 'qu');
  await click(0); assert.equal(await babbleWord(), '');
  await run("window.__babbleExpertGlow.setEnabled(false)");
  await click(1); await click(1); assert.equal(await babbleWord(), '', 'Undo also works with highlights off');
  console.log('ALL PASSED: Babble and legacy Clues last-tile undo, Qu, duplicate letters and shortened previews');
  win.destroy(); app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
