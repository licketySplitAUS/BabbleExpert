'use strict';
const { app, BrowserWindow, clipboard } = require('electron');
const fs = require('node:fs'), path = require('node:path'), http = require('node:http'), assert = require('node:assert/strict');
const { createApp } = require('../../src/app');
const { createDiagnostics } = require('../../src/diagnostics');
app.disableHardwareAcceleration();
for (const name of ['show', 'focus', 'maximize']) BrowserWindow.prototype[name] = function () {};
app.on('web-contents-created', (_event, wc) => wc.setBackgroundThrottling(false));
const dir = fs.mkdtempSync(path.join(process.cwd(), 'be-ui-')); app.setPath('userData', dir);
let copied = ''; clipboard.writeText = value => { copied = value; };
const until = async predicate => { for (let i = 0; i < 150; i++) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 50)); } throw Error('UI test timed out'); };
const deadline = setTimeout(() => app.exit(1), 30000);
app.whenReady().then(async () => {
  const server = http.createServer((req, res) => { res.setHeader('content-type', 'text/html'); res.end(fs.readFileSync(path.join(__dirname, 'fixtures', req.url.startsWith('/babble') ? 'babble.html' : 'clues.html'))); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = 'http://localhost:' + server.address().port;
  const diagnostics = createDiagnostics({ userDataDir: dir, version: '3.2.12.0', endpoint: null });
  const ctx = createApp({ userDataDir: dir, version: '3.2.12.0', diagnostics, telemetryEndpoint: null, urls: { babble: base + '/babble', clues: base + '/clues' }, hosts: { babble: ['localhost'], clues: ['localhost'] } });
  const run = code => ctx.win.webContents.executeJavaScript(code);
  await until(() => run('!!document.getElementById("btnHelp").onclick'));
  ctx.patch({ largeInterface: true });
  await until(() => run('document.body.classList.contains("large-interface")'));
  assert.equal(await run('getComputedStyle(document.body).fontSize'), '16px');
  const before = await run('document.getElementById("slotClues").offsetWidth');
  await run('document.getElementById("spl1").dispatchEvent(new KeyboardEvent("keydown",{key:"ArrowRight",bubbles:true}))');
  await until(async () => await run('document.getElementById("slotClues").offsetWidth') > before);
  assert.ok(await run('Number(document.getElementById("spl1").getAttribute("aria-valuenow"))>0'));
  diagnostics.report('load-failed', { component: 'clues', code: -105 });
  await run('document.getElementById("btnHelp").click()');
  const help = () => BrowserWindow.getAllWindows().find(win => win.getTitle() === 'Babble Expert Help');
  await until(() => help() && !help().webContents.isLoading());
  await help().webContents.executeJavaScript('document.getElementById("copy-support").click()');
  await until(() => copied.includes('3.2.12.0'));
  assert.ok(copied.includes(ctx.settings.data.anonymousId)); assert.ok(copied.includes('-105'));
  assert.doesNotMatch(copied, /localhost|file:\/\/|alpha|bravo/);
  assert.equal(ctx.tour, undefined);
  assert.equal(await help().webContents.executeJavaScript('!!document.getElementById("watch-tour")'), false);
  clearTimeout(deadline); server.close();
  console.log('PASS larger interface, keyboard divider resizing, safe support summary and removed tour link.'); app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
