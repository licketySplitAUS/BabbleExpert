'use strict';
const { app, BrowserWindow, ipcMain } = require('electron');
const fs = require('node:fs'), path = require('node:path'), http = require('node:http'), assert = require('node:assert/strict');
const { createApp } = require('../../src/app');
const { Settings } = require('../../src/settings');
app.disableHardwareAcceleration();
app.on('web-contents-created', (_event, wc) => wc.setBackgroundThrottling(false));
const dir = fs.mkdtempSync(path.join(process.cwd(), 'hints-profile-')); app.setPath('userData', dir);
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const until = async predicate => { for (let i = 0; i < 150; i++) { if (await predicate()) return; await sleep(50); } throw Error('Hint test timed out: ' + predicate.toString()); };
const deadline = setTimeout(() => app.exit(1), 40000);
app.whenReady().then(async () => {
  const server = http.createServer((req, res) => { res.setHeader('content-type', 'text/html'); res.end(fs.readFileSync(path.join(__dirname, 'fixtures', req.url.startsWith('/babble') ? 'babble.html' : 'clues.html'))); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = 'http://localhost:' + server.address().port;
  const ctx = createApp({ userDataDir: dir, telemetryEndpoint: null, telemetryPrompt: false,
    urls: { babble: base + '/babble', clues: base + '/clues' }, hosts: { babble: ['localhost'], clues: ['localhost'] } });
  const run = code => ctx.win.webContents.executeJavaScript(code);
  await until(() => run('!!document.getElementById("btnClueSource").textContent && !!window.expertHints'));
  await until(() => ctx.engine.state.ready && ctx.engine.state.cluesOk);
  ctx.win.show(); ctx.win.focus(); ctx.win.webContents.focus(); await until(() => ctx.win.isFocused());
  await sleep(200);
  const visible = () => ctx.hints.getWindow()?.isVisible() === true;
  const hover = id => run(`document.getElementById(${JSON.stringify(id)}).dispatchEvent(new PointerEvent('pointerover',{bubbles:true}))`);
  assert.ok(ctx.views.babble.getBounds().width > 0);
  const width = id => run(`document.getElementById(${JSON.stringify(id)}).offsetWidth`);
  const clickBar = async id => {
    ctx.views.babble.webContents.focus();
    const point = await run(`(()=>{const r=document.getElementById(${JSON.stringify(id)}).getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+50)}})()`);
    const wc = ctx.win.webContents;
    wc.sendInputEvent({ type: 'mouseMove', ...point });
    wc.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 });
    wc.sendInputEvent({ type: 'mouseUp', ...point, button: 'left', clickCount: 1 });
    await until(() => run(`document.activeElement.id === ${JSON.stringify(id)}`));
    await until(() => ctx.win.webContents.isFocused());
  };
  const press = async (keyCode, modifiers = []) => {
    ctx.win.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers });
    ctx.win.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers });
    await sleep(100);
  };
  const cluesBefore = await width('slotClues');
  await clickBar('spl1'); await press('Right');
  await until(async () => await width('slotClues') === cluesBefore + 10);
  await press('Left', ['shift']);
  await until(async () => await width('slotClues') === cluesBefore - 40);
  await press('Home'); await until(async () => await width('slotClues') === 150);
  ctx.patch({ switchSides: true, cluesW: 260 });
  await until(async () => await width('slotClues') === 260);
  await clickBar('spl1'); await press('Left');
  await until(async () => await width('slotClues') === 270);
  ctx.openResource({ label: 'Resize test', url: base + '/resource' });
  await until(async () => await width('resPane') > 0);
  // Opening a native web view can change focus while its renderer starts.
  // Wait for the resource and its asynchronous layout before testing a click
  // that must transfer focus from Babble back to the resize bar.
  await until(() => !ctx.views.res.webContents.isLoading());
  await until(async () => {
    const expected = await run("(()=>{const r=document.getElementById('slotRes').getBoundingClientRect();return {x:Math.round(r.x),y:Math.round(r.y),width:Math.round(r.width),height:Math.round(r.height)}})()");
    const actual = ctx.views.res.getBounds();
    return Object.keys(expected).every(key => expected[key] === actual[key]);
  });
  const resourcesBefore = await width('resPane');
  await clickBar('spl2'); await press(ctx.settings.data.resourcesLeft ? 'Right' : 'Left');
  await until(async () => await width('resPane') === resourcesBefore + 10);
  await press(ctx.settings.data.resourcesLeft ? 'Left' : 'Right', ['shift']);
  await until(async () => await width('resPane') === resourcesBefore - 40);
  ctx.hideResources(); ctx.patch({ switchSides: false, cluesW: 260 });
  await sleep(150);
  assert.equal(ctx.settings.data.hideHints, false);
  await hover('btnRefresh'); await sleep(500); assert.equal(visible(), false);
  await until(visible);
  assert.equal(ctx.hints.getWindow().isFocusable(), false);
  assert.equal(ctx.win.isFocused(), true);
  assert.match(await ctx.hints.getWindow().webContents.executeJavaScript('document.body.innerText'), /F5/);
  if (process.env.HINT_SCREENSHOT) fs.writeFileSync(process.env.HINT_SCREENSHOT, (await ctx.hints.getWindow().webContents.capturePage()).toPNG());
  ctx.win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' });
  await until(() => !visible());
  ctx.patch({ hideHints: true }); await sleep(100);
  await hover('btnRes'); await sleep(1200); assert.equal(visible(), false);
  ctx.patch({ hideHints: false }); await sleep(100);
  // Restore the tested window explicitly between hover and keyboard scenarios;
  // virtual-display window managers may change focus when a tooltip is hidden.
  ctx.win.focus(); ctx.win.webContents.focus();
  await until(() => ctx.win.isFocused() && ctx.win.webContents.isFocused());
  await sleep(100);
  await run('document.activeElement.blur()');
  await run('document.getElementById("btnHelp").focus()'); await until(visible);
  assert.equal(await run('document.getElementById("btnHelp").getAttribute("aria-describedby")'), 'expert-hint-description');
  await run('document.dispatchEvent(new PointerEvent("pointerdown",{bubbles:true}))'); await until(() => !visible());
  ipcMain.emit('hint', { sender: ctx.views.babble.webContents, senderFrame: ctx.views.babble.webContents.mainFrame }, { text: 'untrusted', rect: { x: 1, y: 1, width: 20, height: 20 } });
  await sleep(100); assert.equal(visible(), false);
  ctx.patch({ largeInterface: true }); await sleep(100);
  await run('document.getElementById("btnRefresh").focus()'); await until(visible);
  assert.equal(await ctx.hints.getWindow().webContents.executeJavaScript('getComputedStyle(document.body).fontSize'), '18px');
  ctx.setAddVisible(true);
  const add = ctx.getAddWindow(); add.focus();
  await until(() => !add.webContents.isLoading() && add.isFocused());
  await add.webContents.executeJavaScript('document.getElementById("chbDontClear").focus()'); await until(visible);
  assert.match(await ctx.hints.getWindow().webContents.executeJavaScript('document.body.innerText'), /Keep your word/);
  assert.equal(add.isFocused(), true);
  assert.equal(await run('document.querySelectorAll("[title]").length'), 0);
  ctx.patch({ hideHints: true }); ctx.settings.flush();
  assert.equal(new Settings(path.join(dir, 'settings.json')).data.hideHints, true);
  await until(() => !visible());
  // Exercise normal closing with a remembered hint owner, rather than app.exit.
  ctx.setAddVisible(false); ctx.win.focus(); ctx.win.webContents.focus();
  ctx.patch({ hideHints: false }); await sleep(100);
  await run('document.getElementById("btnRes").focus()'); await until(visible);
  const caption = ctx.hints.getWindow();
  ctx.win.destroy();
  const afterExit = new Settings(path.join(dir, 'settings.json'));
  assert.equal(afterExit.data.hideHints, true, 'Exiting with hints on saves them off for the next launch');
  assert.equal(afterExit.data.hintsFirstSessionFinished, true, 'The automatic switch-off happens only once');
  assert.equal(caption.isDestroyed(), true);
  assert.equal(ipcMain.listenerCount('hint'), 0);
  clearTimeout(deadline); server.close();
  console.log('PASS click-to-focus resize bars, native arrow/Shift/Home keys, switched sides, delayed hover captions, focus preservation, keyboard hints, Escape/click dismissal, opt-out persistence, native-title suppression, large text, Add controls and untrusted sender rejection.');
  app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
